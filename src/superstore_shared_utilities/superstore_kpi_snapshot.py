"""
==============================================================
Module: KPI run snapshot
==============================================================

Purpose
-------
Record the headline numbers once per pipeline run, to
`{env}_metrics.kpi_run_snapshot`, so a dashboard can show each number for
this run next to the previous run.

Why this exists
---------------
Every run rebuilds the KPI views from Gold, so the previous run's numbers are
gone the moment a new run finishes. A dashboard can show "revenue now" but not
"revenue as of the last run", and a viewer cannot tell whether a jump came
from new data or from history being restated (a late file, a reload, a bug).

Delta time travel looks like it would answer that, but VACUUM removes old
versions after 7 days by default and the pipeline runs weekly, so the previous
run's version would often be gone. One explicit row per run does not expire.

Design rules
------------
1. **One row per run, idempotent.** The row is MERGEd on master_run_id, so a
   retried task replaces its own row instead of adding a second one.
2. **Same definitions as the dashboards.** Customers and orders exclude the
   'Unknown' placeholder rows, as the customer dashboard does; the 30-day
   figures use the same window as the executive tiles.
3. **A failure to record fails the task**, as in superstore_data_quality_checks:
   a snapshot that silently stops being written leaves the dashboards
   comparing against an ever older run.
4. **Pure core, thin shell.** Row construction is pure and unit-tested.
==============================================================
"""

from datetime import datetime

TABLE_NAME = "kpi_run_snapshot"

# Explicit, not inferred: an all-NULL measure (an empty environment) would
# otherwise infer as a different type than a populated one, and MERGE would
# fail on the mismatch.
TABLE_SCHEMA = (
    "master_run_id STRING, env STRING, trigger_type STRING, "
    "run_started_at TIMESTAMP, snapshot_at TIMESTAMP, raw_rows_ingested BIGINT, "
    "data_from DATE, data_through DATE, "
    "revenue_30d DOUBLE, profit_30d DOUBLE, "
    "revenue_total DOUBLE, profit_total DOUBLE, orders_total BIGINT, customers_total BIGINT"
)

_MEASURES_DOUBLE = ("revenue_30d", "profit_30d", "revenue_total", "profit_total")
_MEASURES_BIGINT = ("raw_rows_ingested", "orders_total", "customers_total")


def measures_sql(catalog, semantic_schema, metrics_schema, master_run_id):
    """
    One query returning every measure for the snapshot row, as a single row.

    master_run_id is interpolated as a string literal; it is generated by the
    pipeline's own init task (a UUID), never user input.
    """
    sl = f"{catalog}.{semantic_schema}"
    mt = f"{catalog}.{metrics_schema}"
    return f"""
    WITH daily AS (
      SELECT order_date, total_sales, total_profit FROM {sl}.metrics_daily_kpi
    ),
    bounds AS (
      SELECT MIN(order_date) AS data_from, MAX(order_date) AS data_through FROM daily
    ),
    window_30d AS (
      SELECT SUM(d.total_sales) AS revenue_30d, SUM(d.total_profit) AS profit_30d
      FROM daily d CROSS JOIN bounds b
      WHERE d.order_date > DATE_SUB(b.data_through, 30)
    ),
    totals AS (
      SELECT SUM(total_sales) AS revenue_total, SUM(total_profit) AS profit_total FROM daily
    ),
    customers AS (
      SELECT SUM(total_orders) AS orders_total, COUNT(DISTINCT customer_id) AS customers_total
      FROM {sl}.customer_kpi
      WHERE region <> 'Unknown' AND segment <> 'Unknown'
    ),
    this_run AS (
      SELECT MIN(start_ts) AS run_started_at, MAX(rows_read) AS raw_rows_ingested
      FROM {mt}.bronze_layer_entity_metrics
      WHERE master_run_id = '{master_run_id}'
    )
    SELECT * FROM bounds, window_30d, totals, customers, this_run
    """


def snapshot_row(env, master_run_id, trigger_type, measures, snapshot_at):
    """
    Build the snapshot row from the measures query result. Pure.

    `measures` is any mapping with the measure columns -- a Spark Row (via
    asDict) or a plain dict in tests. A missing or NULL measure stays None:
    an empty environment records "no data", not zero revenue.
    """
    if not isinstance(snapshot_at, datetime):
        raise TypeError("snapshot_at must be a datetime")

    def _get(key):
        return measures.get(key) if hasattr(measures, "get") else measures[key]

    row = {
        "master_run_id": master_run_id,
        "env": env,
        "trigger_type": (trigger_type or "unknown").lower(),
        "run_started_at": _get("run_started_at"),
        "snapshot_at": snapshot_at,
        "data_from": _get("data_from"),
        "data_through": _get("data_through"),
    }
    for key in _MEASURES_DOUBLE:
        value = _get(key)
        row[key] = None if value is None else float(value)
    for key in _MEASURES_BIGINT:
        value = _get(key)
        row[key] = None if value is None else int(value)
    return row


def record_snapshot(spark, catalog, metrics_schema, semantic_schema, row):
    """
    MERGE the row into `{metrics_schema}.kpi_run_snapshot` and (re)create the
    view of the same name in the semantic layer. Raises on any failure (rule 3).

    The view exists because the business dashboards read the semantic layer
    only; the run record itself belongs with the other run metrics.
    """
    table = f"{catalog}.{metrics_schema}.{TABLE_NAME}"
    view = f"{catalog}.{semantic_schema}.{TABLE_NAME}"
    spark.sql(f"CREATE TABLE IF NOT EXISTS {table} ({TABLE_SCHEMA})")
    spark.createDataFrame([row], schema=TABLE_SCHEMA).createOrReplaceTempView("kpi_run_snapshot_new")
    spark.sql(f"""
        MERGE INTO {table} AS t
        USING kpi_run_snapshot_new AS s
        ON t.master_run_id = s.master_run_id
        WHEN MATCHED THEN UPDATE SET *
        WHEN NOT MATCHED THEN INSERT *
    """)
    spark.sql(f"CREATE OR REPLACE VIEW {view} AS SELECT * FROM {table}")
    return table
